      const firstVisit = await createBooking(customer,scheduled,randomUUID());
      await updateBooking(provider,firstVisit.id,{ action: "accept", visitMinutes: 60 });
      const overlap = await createBooking(customer,{ ...scheduled, preferredTime: "11:00" },randomUUID());
      let preview = (await getWorkspace(provider)).requests!.find(r => r.id === overlap.id)!;
      assert.equal(preview.availability,"conflict");
      assert.ok(!JSON.stringify(preview).includes(payload.description));
      await assert.rejects(updateBooking(provider,overlap.id,{ action: "accept" }),{ status: 409 });
      // Half-open reservations allow a visit exactly after the previous visit + buffer.
      const adjacent = await createBooking(customer,{ ...scheduled, preferredTime: "11:30" },randomUUID());
      await updateBooking(provider,adjacent.id,{ action: "accept", visitMinutes: 60 });
      const longVisit = await createBooking(customer,{ ...scheduled, preferredTime: "08:00" },randomUUID());
      assert.equal((await getWorkspace(provider)).requests!.find(r => r.id === longVisit.id)!.availability,"available");
      await assert.rejects(updateBooking(provider,longVisit.id,{ action: "accept", visitMinutes: 240 }),{ status: 409 });
      await updateBooking(provider,firstVisit.id,{ action: "progress", status: "on_the_way" });
      await assert.rejects(updateBooking(provider,adjacent.id,{ action: "progress", status: "on_the_way" }),{ status: 409 });
      await updateBooking(provider,firstVisit.id,{ action: "progress", status: "inspecting" });
      await executeAction(provider,{ type: "estimate", bookingId: firstVisit.id, items: [] });
      const [quote] = await db.select().from(t.estimates).where(eq(t.estimates.bookingId,firstVisit.id));
      await executeAction(customer,{ type: "decide-estimate", estimateId: quote.id, approved: false });
      // Cancel the adjacent fixture so the overlap is free after closure.
      await updateBooking(customer,adjacent.id,{ action: "cancel", reason: "Release the temporary adjacent appointment" });
      preview = (await getWorkspace(provider)).requests!.find(r => r.id === overlap.id)!;
      assert.equal(preview.availability,"available");
      await updateBooking(provider,overlap.id,{ action: "accept" });
      await assert.rejects(db.update(t.bookings).set({ visitMinutes: 120, reservedUntil: new Date(startTime(firstVisit) + 150 * 60000) }).where(eq(t.bookings.id,firstVisit.id)));
      // Expired requests remain visible and cannot be accepted.
      const expired = await createBooking(customer,{ ...scheduled, date: localDate(41) },randomUUID());
      const past = normalizeSchedule({ scheduleMode: "scheduled", date: "2020-01-01", preferredTime: "10:00" },-Infinity);
      await db.update(t.bookings).set(past).where(eq(t.bookings.id,expired.id));
      assert.equal((await getWorkspace(provider)).requests!.find(r => r.id === expired.id)!.availability,"expired");
      await assert.rejects(updateBooking(provider,expired.id,{ action: "accept" }),{ status: 409 });
      await executeAction(customer,{ type: "reschedule", bookingId: expired.id, scheduleMode: "asap" });
      assert.equal((await getWorkspace(provider)).requests!.find(r => r.id === expired.id)!.scheduleMode,"asap");
      // SQL independently rejects assigned overlap, not just application checks.
      const blocked = await createBooking(customer,{ ...scheduled, preferredTime: "11:00" },randomUUID());
      await assert.rejects(db.update(t.bookings).set({ providerId: provider.id, status: "accepted" }).where(eq(t.bookings.id,blocked.id)),e => !!e && typeof e === "object" && "cause" in e && (e.cause as { code: string }).code === "23P01");
      // Different preferred times still conflict under simultaneous acceptance.
